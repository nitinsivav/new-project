package com.project.repository;

import com.project.model.User;
import org.junit.jupiter.api.Test;
import java.sql.SQLException;
import static org.junit.jupiter.api.Assertions.*;

public class UserRepositoryTest {

    @Test
    public void testSaveUser_Success() throws SQLException {
        UserRepository repository = new UserRepository();

        String uniqueEmail = "test" + System.currentTimeMillis() + "@project.com";
        User newUser = new User("Test User", "1234567890", uniqueEmail, "hashed_pwd_here");

        User savedUser = repository.save(newUser);
        
        assertNotNull(savedUser.getId(), "User ID should be generated by the database");
        assertEquals(uniqueEmail, savedUser.getEmail());

    }
}
